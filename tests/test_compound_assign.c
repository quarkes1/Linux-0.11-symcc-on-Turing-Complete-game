/* tests/test_compound_assign.c — M2 Task 3 验收：复合赋值 */
int main(void) {
    int a[3] = {10, 5, 2};
    int *p = a;
    a[0] += 5;   /* 15 */
    a[1] -= 1;   /* 4 */
    a[2] *= 3;   /* 6 */
    p[0] |= 8;   /* 15|8 = 15 */
    p[1] &= 3;   /* 4&3 = 0 */
    p[2] ^= 1;   /* 6^1 = 7 */
    a[0] <<= 1;  /* 30 */
    a[1] >>= 1;  /* 0 */
    a[2] %= 2;   /* 1 */
    return a[0] + a[1] + a[2];   /* 30 + 0 + 1 = 31（计划注释 30+2+0 有误） */
}
